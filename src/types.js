export const CODES = Object.keys(TYPES);

/** 4軸の判定結果からコードを組み立てる */
export function toCode(axes) {
  return (
    (axes.high ? 'H' : 'L') +
    (axes.dynamic ? 'D' : 'E') +
    (axes.fast ? 'F' : 'S') +
    (axes.continuous ? 'C' : 'B')
  );
}

/** 「モノクロ型（LEFB）」の形に整える */
export function label(code) {
  return `${TYPES[code].name}（${code}）`;
}
